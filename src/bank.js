function papersFor(major) {
  fixSharedAnswers();
  const category = BY_CATEGORY[major.category] || BY_CATEGORY.通用;
  const pool = [...SHARED, ...category];
  const historyA = take(pool, major.id % pool.length, 12).map((template) => fill(template, major));
  const historyB = take(pool, (major.id + 8) % pool.length, 12).map((template) => fill(template, major));
  const papers = [
    { kind: 'history', year: 2024, title: '2024 历年题型套卷', minutes: 40, questions: historyA },
    { kind: 'history', year: 2025, title: '2025 历年题型套卷', minutes: 45, questions: historyB },
  ];
  if (major.outline_status === 'published') {
    papers.push({
      kind: 'current',
      year: 2026,
      title: '2026 考纲套卷',
      minutes: 40,
      questions: take(pool, (major.id + 3) % pool.length, 10).map((template) => fill(template, major)),
    });
  }
  return papers;
}

export function ensureBank() {
  const created = nowIso();
  const existingUser = db.prepare('SELECT id FROM users WHERE phone = ?').get(FULL_PHONE);
  if (!existingUser) {
    db.prepare(`
      INSERT INTO users (phone, name, password_hash, role, paid_until, created_at)
      VALUES (?, ?, ?, 'student', '2027-06-30', ?)
    `).run(FULL_PHONE, '全量学生', hashPassword('student123'), created);
  } else {
    db.prepare(`UPDATE users SET paid_until = '2027-06-30' WHERE phone = ? AND role = 'student'`).run(FULL_PHONE);
  }
  const marker = db.prepare('SELECT value FROM settings WHERE key = ?').get('bank_pack');
  if (marker?.value === PACK) return;

  const majors = db.prepare(`
    SELECT m.id, m.name, m.category, m.outline_status, s.name AS school_name
    FROM majors m JOIN schools s ON s.id = m.school_id
    WHERE m.status = 'published'
  `).all();
  const insertQuestion = db.prepare(`
    INSERT INTO questions (
      major_id, year, kind, module, stem, options_json, answer, explanation, difficulty, status, origin, created_at, qtype
    ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 'published', 'paper', ?, ?)
  `);
  const insertPaper = db.prepare(`
    INSERT INTO papers (major_id, kind, title, year, minutes, question_ids_json, note, created_at)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?)
  `);
  const note = '仿真套卷，按历年题型和考纲模块组卷，不是院校公布的原卷。';
  db.exec('BEGIN');
  try {
    majors.forEach((major) => {
      papersFor(major).forEach((paper) => {
        const ids = paper.questions.map((question) => Number(insertQuestion.run(
          major.id, paper.year, paper.kind, question.module, question.stem,
          JSON.stringify(question.options), question.answer, question.explanation,
          question.difficulty, created, question.qtype,
        ).lastInsertRowid));
        insertPaper.run(major.id, paper.kind, paper.title, paper.year, paper.minutes, JSON.stringify(ids), note, created);
      });
    });
    db.prepare(`
      INSERT INTO settings (key, value) VALUES ('bank_pack', ?)
      ON CONFLICT(key) DO UPDATE SET value = excluded.value
    `).run(PACK);
    db.exec('COMMIT');
  } catch (error) {
    db.exec('ROLLBACK');
    throw error;
  }
}
