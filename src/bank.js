function fill(template, major) {
  const stem = template.stem.replaceAll('{major}', major.name).replaceAll('{school}', major.school_name);
  return { ...template, stem, options: [...template.options] };
}

function take(list, offset, count) {
  const picked = [];
  for (let index = 0; index < count; index += 1) picked.push(list[(offset + index) % list.length]);
  return picked;
}

